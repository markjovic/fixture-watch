// scripts/test/mock-playhq.cjs
//
// THE HARNESS'S NETWORK. Preloaded with `node --require`, so fixture-watch.js runs
// completely unmodified — nothing in the production code knows this exists, and
// nothing in it may be changed to make a test pass.
//
// It replaces global fetch for exactly two hosts (api.playhq.com and
// api.pushover.net) and records every call to FW_CALLLOG, including the `tenant`
// header and the `Cookie` header. Those two recordings are what prove the
// per-tenant session: a basketball cookie arriving on the afl tenant is visible in
// the log rather than looking like an authentication fault.
//
// FW_FAST_SLEEP=1 clamps setTimeout so the real backoff ladders (5s/15s transient,
// 20/40/60/80s session, 15 minutes bootstrap-refused) run in milliseconds. The
// ladders themselves are untouched — only the clock is.

'use strict';

const fs = require('fs');

const SCENARIO = JSON.parse(fs.readFileSync(process.env.FW_SCENARIO, 'utf8'));
const LOGFILE  = process.env.FW_CALLLOG;
const calls    = [];
const counters = new Map();

function log(entry) {
  calls.push(entry);
  fs.writeFileSync(LOGFILE, JSON.stringify(calls, null, 2));
}

if (process.env.FW_FAST_SLEEP === '1') {
  const realSetTimeout = global.setTimeout;
  global.setTimeout = function (fn, ms, ...rest) {
    return realSetTimeout(fn, (typeof ms === 'number' && ms > 20) ? 2 : ms, ...rest);
  };
  global.setTimeout.__promisify__ = realSetTimeout.__promisify__;
}

function makeRes(status, rawText, setCookie) {
  return {
    status,
    async text() { return rawText; },
    headers: {
      getSetCookie: () => (setCookie || []),
      get: (n) => (String(n).toLowerCase() === 'set-cookie' && setCookie && setCookie.length ? setCookie[0] : null),
    },
  };
}

const WAF_BODY = '<!DOCTYPE HTML><html><head><title>ERROR: The request could not be satisfied</title></head><body>Request blocked. We can\'t connect to the server for this app or website at this time. Generated by cloudfront.</body></html>';

class TimeoutError extends Error {
  constructor() { super('The operation was aborted due to timeout'); this.name = 'TimeoutError'; }
}

// Turn a response spec into an answer, honouring the "fail N times first" knobs.
function answer(key, spec) {
  if (!spec) return makeRes(200, JSON.stringify({ data: {} }));
  const n = (counters.get(key) || 0) + 1;
  counters.set(key, n);

  if (spec.throwTimes && n <= spec.throwTimes) throw new TimeoutError();
  if (spec.transient && n <= spec.transient)   return makeRes(spec.transientStatus || 504, 'gateway');

  if (spec.waf)    return makeRes(spec.status || 403, WAF_BODY);
  if (spec.status && spec.status !== 200) return makeRes(spec.status, spec.body || 'error');
  if (spec.gqlErrors) return makeRes(200, JSON.stringify({ errors: spec.gqlErrors.map(m => ({ message: m })) }));
  return makeRes(200, JSON.stringify({ data: spec.data === undefined ? {} : spec.data }));
}

global.fetch = async function (url, opts) {
  const u = String(url);
  const headers = (opts && opts.headers) || {};

  // ── Pushover ──────────────────────────────────────────────────────────────
  if (u.indexOf('pushover.net') !== -1) {
    const form = new URLSearchParams(String(opts.body || ''));
    const mode = (SCENARIO.pushover && SCENARIO.pushover.mode) || 'ok';
    const entry = {
      kind: 'pushover',
      title: form.get('title'), message: form.get('message'),
      url: form.get('url') || null, urlTitle: form.get('url_title') || null,
      priority: form.get('priority'), accepted: mode === 'ok',
    };
    log(entry);
    if (mode === 'ok') return makeRes(200, JSON.stringify({ status: 1 }));
    return makeRes(400, JSON.stringify({ status: 0, errors: ['harness: rejected on purpose'] }));
  }

  // ── GitHub workflow dispatch (fast publish on FINAL) ──────────────────────
  if (u.indexOf('api.github.com') !== -1) {
    const body = JSON.parse(String(opts.body || '{}'));
    const m = u.match(/repos\/(.+?)\/actions\/workflows\/(.+?)\/dispatches/);
    const entry = {
      kind: 'dispatch',
      repo: m ? m[1] : null, workflow: m ? m[2] : null,
      ref: body.ref, inputs: body.inputs || {},
      auth: String(headers.Authorization || ''),
    };
    log(entry);
    const mode = (SCENARIO.dispatch && SCENARIO.dispatch.mode) || 'ok';
    if (mode === 'ok') return makeRes(204, '');
    return makeRes(422, JSON.stringify({ message: 'harness: refused on purpose' }));
  }

  // ── PlayHQ ────────────────────────────────────────────────────────────────
  const body   = JSON.parse(String(opts.body || '{}'));
  const op     = body.operationName;
  const tenant = headers.tenant;
  const cookie = headers.Cookie || null;
  const t      = (SCENARIO.tenants && SCENARIO.tenants[tenant]) || {};

  if (op === 'TenantConfig' || op === 'ProfileSearch') {
    log({ kind: 'session', tenant, op });
    if (t.session === 'waf') return makeRes(403, WAF_BODY);
    if (t.session === 'nocookie') return makeRes(200, JSON.stringify({ data: {} }));
    return makeRes(200, JSON.stringify({ data: {} }), [
      `phq_tier=tier-${tenant}; Path=/`,
      `phq_session=sess-${tenant}; Path=/`,
      `phq_sub=sub-${tenant}; Path=/`,
    ]);
  }

  const id = body.variables ? (body.variables.profileID || body.variables.teamID || body.variables.gradeID) : null;
  const bucket = op === 'PublicProfileTeams' ? 'profile'
               : op === 'TeamFixture'        ? 'fixture'
               : op === 'gradeRounds'        ? 'grade' : 'unknown';
  log({ kind: bucket, tenant, op, id, cookie });

  const spec = (t[bucket] || {})[id];
  if (!spec && bucket === 'fixture') return makeRes(200, JSON.stringify({ data: { discoverTeam: null, discoverTeamFixture: [] } }));
  if (!spec && bucket === 'profile') return makeRes(200, JSON.stringify({ data: { publicProfileTeams: [] } }));
  if (!spec && bucket === 'grade')   return makeRes(200, JSON.stringify({ data: { discoverGrade: null } }));
  return answer(`${tenant}|${bucket}|${id}`, spec);
};
